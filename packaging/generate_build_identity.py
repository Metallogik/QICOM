"""Record which commit a build was made from, before the build is made.

Writes `qicom/_build_identity.py`, which qicom.build_identity imports at
runtime. A distributed bundle must be able to name its own source without
carrying a `.git` directory, and the only moment that information is
available for certain is while the build is still standing in the checkout.

Run it in the packaging workflow immediately before PyInstaller:

    python packaging/generate_build_identity.py

The generated module is deliberately untracked (see .gitignore): it describes
one build, and a committed copy would make every later checkout claim that
build's revision.
"""

from __future__ import annotations

import argparse
import runpy
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "qicom" / "_build_identity.py"

_TEMPLATE = '''"""Generated by packaging/generate_build_identity.py - do not edit.

Describes the one build this file was written for. Read through
qicom.build_identity, never imported directly.
"""

BUILD_REVISION = {revision!r}
SOURCE_DIRTY = {dirty!r}
VERSION = {version!r}
'''


def _git(*arguments: str) -> str:
    completed = subprocess.run(
        ["git", *arguments],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return completed.stdout.strip()


def _package_version() -> str:
    """Read the version the same way qicom.spec does - by executing the
    module rather than importing the package, which needs no dependencies
    installed."""
    return str(runpy.run_path(str(REPO_ROOT / "qicom" / "__version__.py"))["__version__"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Where to write the generated module (default: qicom/_build_identity.py).",
    )
    parser.add_argument(
        "--require-clean",
        action="store_true",
        help=(
            "Fail instead of recording SOURCE_DIRTY=True. Use for a release "
            "build, where a bundle built from uncommitted changes is not "
            "reproducible from any commit."
        ),
    )
    arguments = parser.parse_args(argv)

    try:
        revision = _git("rev-parse", "HEAD")
        dirty = bool(_git("status", "--porcelain"))
    except (OSError, subprocess.CalledProcessError) as exc:
        print(f"error: cannot read the git revision of {REPO_ROOT}: {exc}", file=sys.stderr)
        return 1

    if dirty and arguments.require_clean:
        print(
            "error: refusing to record a build identity for a modified checkout; "
            "commit or stash the changes first.",
            file=sys.stderr,
        )
        return 1

    version = _package_version()
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(
        _TEMPLATE.format(revision=revision, dirty=dirty, version=version), encoding="utf-8"
    )
    marker = " (modified source)" if dirty else ""
    print(f"Build identity: {version} {revision}{marker} -> {arguments.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
